# OntoDB One-Click Deployment Script (Windows PowerShell)
#
# Usage:
#   .\scripts\deploy.ps1 [OPTIONS]
#
# Options:
#   -Mode MODE        Deployment mode: docker | k8s | local (default: docker)
#   -Edition EDITION  Edition: oss | standard | gov (default: oss)
#   -Namespace NS     Kubernetes namespace (default: ontodb)
#   -Replicas N       Number of replicas for K8s (default: 3)
#   -SkipMonitoring   Skip monitoring stack setup
#   -SkipBackup       Skip backup configuration
#   -Help             Show this help

param(
    [ValidateSet("docker", "k8s", "local")]
    [string]$Mode = "docker",

    [ValidateSet("oss", "standard", "gov")]
    [string]$Edition = "oss",

    [string]$Namespace = "ontodb",

    [int]$Replicas = 3,

    [switch]$SkipMonitoring,

    [switch]$SkipBackup,

    [switch]$Help
)

# Colors
$Green = "`e[32m"
$Yellow = "`e[33m"
$Blue = "`e[34m"
$Red = "`e[31m"
$NC = "`e[0m"

# Show help
if ($Help) {
    Write-Host @"
OntoDB One-Click Deployment Script

Usage:
  .\scripts\deploy.ps1 [OPTIONS]

Options:
  -Mode MODE        Deployment mode: docker | k8s | local (default: docker)
  -Edition EDITION  Edition: oss | standard | gov (default: oss)
  -Namespace NS     Kubernetes namespace (default: ontodb)
  -Replicas N       Number of replicas for K8s (default: 3)
  -SkipMonitoring   Skip monitoring stack setup
  -SkipBackup       Skip backup configuration
  -Help             Show this help
"@
    exit 0
}

# Banner
Write-Host @"

